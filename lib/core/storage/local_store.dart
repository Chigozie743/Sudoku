import 'package:sudoku/constants/utils/export_file.dart';

///////////////////////////////////////////////////////////////////////////////////////////////////
/// LOCAL STORE
///////////////////////////////////////////////////////////////////////////////////////////////////
class LocalStore {
  LocalStore(this.preferences);
  final SharedPreferences preferences;

  ///////////////////////////////////////////////////////////////////////////////////////////////////
  /// HIGHEST UNLOCKED LEVEL
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  int get unlockedLevel => preferences.getInt('sudoku.unlockedLevel') ?? 1;

  Future<void> setUnlockedLevel(int level) =>
      preferences.setInt('sudoku.unlockedLevel', level);

  ///////////////////////////////////////////////////////////////////////////////////////////////////
  /// BEST TIME PER LEVEL, IN SECONDS
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  int? bestSeconds(int level) => preferences.getInt('sudoku.best.$level');

  Future<void> setBestSeconds(int level, int seconds) =>
      preferences.setInt('sudoku.best.$level', seconds);
}
