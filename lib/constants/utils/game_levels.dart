import 'package:sudoku/constants/utils/export_file.dart';

///////////////////////////////////////////////////////////////////////////////////////////////////
/// GAME LEVELS — ADD A LEVEL BY ADDING AN ENTRY; THE BOARD, SOLVER AND PAD ADAPT TO ITS LAYOUT
///////////////////////////////////////////////////////////////////////////////////////////////////
class GameLevels {
  GameLevels._();

  static const List<GameLevel> all = [
    ///////////////////////////////////////////////////////////////////////////////////////////////
    /// LEVEL 1 — ONE 3×3 TILE, DIGITS 1–9
    ///////////////////////////////////////////////////////////////////////////////////////////////
    GameLevel(
      number: 1,
      difficulty: 'Easy',
      layout: BoardLayout(
        boxesAcross: 1,
        boxesDown: 1,
        boxWidth: 3,
        boxHeight: 3,
      ),
      clues: 5,
    ),

    ///////////////////////////////////////////////////////////////////////////////////////////////
    /// LEVEL 2 — 2×2 TILES, EACH 2×2, DIGITS 1–4
    ///////////////////////////////////////////////////////////////////////////////////////////////
    GameLevel(
      number: 2,
      difficulty: 'Easy',
      layout: BoardLayout(
        boxesAcross: 2,
        boxesDown: 2,
        boxWidth: 2,
        boxHeight: 2,
      ),
      clues: 7,
    ),
  ];

  ///////////////////////////////////////////////////////////////////////////////////////////////////
  /// LOOK UP A LEVEL BY NUMBER
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  static GameLevel byNumber(int number) =>
      all.firstWhere((level) => level.number == number);

  ///////////////////////////////////////////////////////////////////////////////////////////////////
  /// THE LEVEL AFTER THIS ONE, IF ANY
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  static GameLevel? after(GameLevel level) {
    final index = all.indexOf(level);
    return index >= 0 && index + 1 < all.length ? all[index + 1] : null;
  }
}
