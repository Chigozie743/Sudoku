import 'package:sudoku/constants/utils/export_file.dart';

///////////////////////////////////////////////////////////////////////////////////////////////////
/// GAME REPOSITORY CONTRACT
///////////////////////////////////////////////////////////////////////////////////////////////////
abstract class GameRepositoryAbstract {
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  /// A NEW PUZZLE FOR THE LEVEL
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  SudokuPuzzle newPuzzle(GameLevel level);

  ///////////////////////////////////////////////////////////////////////////////////////////////////
  /// SAVED PROGRESS
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  int get unlockedLevel;
  Map<int, int> bestTimes();

  ///////////////////////////////////////////////////////////////////////////////////////////////////
  /// RECORD A WIN — UNLOCKS THE NEXT LEVEL AND KEEPS THE BEST TIME
  ///////////////////////////////////////////////////////////////////////////////////////////////////
  Future<void> recordWin(GameLevel level, Duration time);
}
